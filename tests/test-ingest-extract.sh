#!/usr/bin/env bash
# tests/test-ingest-extract.sh — INGEST-01 (extraction side), D-05 and D-15:
# skills/dossier-ingest/scripts/extract-text.sh, the pdftotext wrapper private
# to the ingest skill.
#
# Contract under test (fixed by plan 04-03, reported from by the ingest skill):
#   0  stdout "extracted: <stem>.txt"  a new .txt written next to the PDF
#   0  stdout "exists: <stem>.txt"     already there (file or symlink), untouched
#   64 usage: no argument, not a .pdf, or no such file
#   65 no text layer (a scan): nothing written
#   69 pdftotext not on PATH: install hint on stderr, nothing written (D-15)
#   1  pdftotext failed, nothing written
#
# Every run of the script is `/bin/bash script ...`, so the macOS system bash
# 3.2 is what is tested. Every PDF is generated by tests/fixtures/make-pdf.py
# into a mktemp folder shaped like sources/received/; none is committed. The
# positive cases are reported with skip() when pdftotext is not on PATH.
set -u

# shellcheck source=./lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

SCRIPT="$REPO_ROOT/skills/dossier-ingest/scripts/extract-text.sh"
MAKE_PDF="$REPO_ROOT/tests/fixtures/make-pdf.py"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# The last run's stdout, stderr and exit status, set by run_ex().
EX_OUT=""
EX_ERR=""
EX_STATUS=0

# run_ex ARG... — runs the script under /bin/bash (bash 3.2 on macOS) with a
# fresh, dedicated TMPDIR in $CASE_TMP so a leaked temporary file is visible.
# stderr goes through a mktemp file created beside nothing under test.
run_ex() {
  local err_file
  err_file="$(mktemp "$WORK/err.XXXXXX")"
  CASE_TMP="$(mktemp -d "$WORK/tmp.XXXXXX")"
  EX_STATUS=0
  EX_OUT="$(TMPDIR="$CASE_TMP" /bin/bash "$SCRIPT" "$@" 2>"$err_file")" || EX_STATUS=$?
  EX_ERR="$(cat "$err_file")"
  rm -f "$err_file"
}

# sha FILE — the sha256 of FILE (shasum on macOS, sha256sum on Linux).
sha() {
  if command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | cut -d' ' -f1
  else
    sha256sum "$1" | cut -d' ' -f1
  fi
}

# new_sources — a fresh folder shaped like sources/received/; echoes its path.
new_sources() {
  local d
  d="$(mktemp -d "$WORK/dossier.XXXXXX")"
  mkdir -p "$d/sources/received"
  echo "$d/sources/received"
}

# --- the script exists, is executable, and parses under bash 3.2 ------------
assert_file "$SCRIPT"
assert_exec "$SCRIPT"
assert_file "$MAKE_PDF"
/bin/bash -n "$SCRIPT" 2>/dev/null
assert_eq 0 "$?" 'extract-text.sh parses under /bin/bash'

if ! command -v pdftotext >/dev/null 2>&1; then
  skip 'pdftotext not on PATH: the positive extraction cases were not run'
  finish
fi

# --- make-pdf.py: one page per argument, readable by pdftotext ---------------
G="$(new_sources)"
python3 "$MAKE_PDF" "$G/gen.pdf" 'Hello' '@empty' '@scan' >/dev/null 2>&1
assert_eq 0 "$?" 'make-pdf.py writes a three-page PDF'
assert_eq 3 "$(pdftotext -- "$G/gen.pdf" - 2>/dev/null | tr -cd '\f' | wc -c | tr -d ' ')" \
  'pdftotext reads three pages from the generated PDF'
assert_eq 1 "$(ls -A "$G" | wc -l | tr -d ' ')" 'make-pdf.py writes only OUT'

# --- happy path: two pages, accents, markers, PDF untouched ------------------
D="$(new_sources)"
python3 "$MAKE_PDF" "$D/2026-10-01_brochure.pdf" \
  'Brochure Été 2026, price 1,250 euros' 'Second page'
before="$(sha "$D/2026-10-01_brochure.pdf")"
run_ex "$D/2026-10-01_brochure.pdf"
assert_eq 0 "$EX_STATUS" 'extract: exit 0'
assert_eq "extracted: $D/2026-10-01_brochure.txt" "$EX_OUT" 'extract: stdout names the .txt'
assert_file "$D/2026-10-01_brochure.txt"
assert_grep '^--- page 1 ---$' "$D/2026-10-01_brochure.txt"
assert_grep '^--- page 2 ---$' "$D/2026-10-01_brochure.txt"
assert_grep 'Été' "$D/2026-10-01_brochure.txt"
assert_grep '1,250' "$D/2026-10-01_brochure.txt"
assert_eq "$before" "$(sha "$D/2026-10-01_brochure.pdf")" 'extract: the PDF is unchanged'
assert_eq 0 "$(ls -A "$CASE_TMP" | wc -l | tr -d ' ')" 'extract: TMPDIR left empty'

# --- empty pages are skipped but keep their number ---------------------------
E="$(new_sources)"
python3 "$MAKE_PDF" "$E/gap.pdf" 'Alpha text' '@empty' 'Gamma text'
run_ex "$E/gap.pdf"
assert_eq 0 "$EX_STATUS" 'empty page: exit 0'
assert_grep '^--- page 1 ---$' "$E/gap.txt"
assert_not_grep '^--- page 2 ---$' "$E/gap.txt"
assert_grep '^--- page 3 ---$' "$E/gap.txt"
assert_grep 'Gamma text' "$E/gap.txt"

# --- uppercase .PDF and a path holding spaces --------------------------------
U="$(new_sources)"
python3 "$MAKE_PDF" "$U/Upper Case.PDF" 'Upper text'
run_ex "$U/Upper Case.PDF"
assert_eq 0 "$EX_STATUS" '.PDF: exit 0'
assert_file "$U/Upper Case.txt"
assert_eq "extracted: $U/Upper Case.txt" "$EX_OUT" '.PDF: stdout names the .txt'

finish
