#!/usr/bin/env bash
# tests/test-ingest-extract.sh — INGEST-01 (extraction side), D-05 and D-15:
# skills/dossier-ingest/scripts/extract-text.sh, the pdftotext wrapper private
# to the ingest skill.
#
# Contract under test (fixed by plan 04-03, reported from by the ingest skill):
#   0  stdout "extracted: <stem>.txt"  a new .txt written next to the PDF
#   0  stdout "exists: <stem>.txt"     already there (file or symlink), untouched
#   64 usage: no argument, not a .pdf, or no such file
#   65 no text layer (a scan): nothing written
#   69 pdftotext not on PATH: install hint on stderr, nothing written (D-15)
#   1  pdftotext failed, nothing written
#
# Every run of the script is `/bin/bash script ...`, so the macOS system bash
# 3.2 is what is tested. Every PDF is generated by tests/fixtures/make-pdf.py
# into a mktemp folder shaped like sources/received/; none is committed. The
# positive cases are reported with skip() when pdftotext is not on PATH.
set -u

# shellcheck source=./lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

SCRIPT="$REPO_ROOT/skills/dossier-ingest/scripts/extract-text.sh"
MAKE_PDF="$REPO_ROOT/tests/fixtures/make-pdf.py"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# EX_PATH — when non-empty, the PATH the next run_ex() gives the script (to hide
# pdftotext or to put a fake one first). Reset to empty after each use.
EX_PATH=""

# The last run's stdout, stderr and exit status, set by run_ex().
EX_OUT=""
EX_ERR=""
EX_STATUS=0

# run_ex ARG... — runs the script under /bin/bash (bash 3.2 on macOS) with a
# fresh, dedicated TMPDIR in $CASE_TMP so a leaked temporary file is visible.
# stderr goes through a mktemp file created beside nothing under test.
run_ex() {
  local err_file
  err_file="$(mktemp "$WORK/err.XXXXXX")"
  CASE_TMP="$(mktemp -d "$WORK/tmp.XXXXXX")"
  EX_STATUS=0
  EX_OUT="$(PATH="${EX_PATH:-$PATH}" TMPDIR="$CASE_TMP" /bin/bash "$SCRIPT" "$@" 2>"$err_file")" || EX_STATUS=$?
  EX_ERR="$(cat "$err_file")"
  rm -f "$err_file"
}

# tmp_clean LABEL — the dedicated TMPDIR of the last run_ex() is empty again.
tmp_clean() {
  assert_eq 0 "$(ls -A "$CASE_TMP" | wc -l | tr -d ' ')" "$1: TMPDIR left empty"
}

# sha FILE — the sha256 of FILE (shasum on macOS, sha256sum on Linux).
sha() {
  if command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | cut -d' ' -f1
  else
    sha256sum "$1" | cut -d' ' -f1
  fi
}

# new_sources — a fresh folder shaped like sources/received/; echoes its path.
new_sources() {
  local d
  d="$(mktemp -d "$WORK/dossier.XXXXXX")"
  mkdir -p "$d/sources/received"
  echo "$d/sources/received"
}

# --- the script exists, is executable, and parses under bash 3.2 ------------
assert_file "$SCRIPT"
assert_exec "$SCRIPT"
assert_file "$MAKE_PDF"
/bin/bash -n "$SCRIPT" 2>/dev/null
assert_eq 0 "$?" 'extract-text.sh parses under /bin/bash'

if ! command -v pdftotext >/dev/null 2>&1; then
  skip 'pdftotext not on PATH: the positive extraction cases were not run'
  finish
fi

# --- make-pdf.py: one page per argument, readable by pdftotext ---------------
G="$(new_sources)"
python3 "$MAKE_PDF" "$G/gen.pdf" 'Hello' '@empty' '@scan' >/dev/null 2>&1
assert_eq 0 "$?" 'make-pdf.py writes a three-page PDF'
assert_eq 3 "$(pdftotext -- "$G/gen.pdf" - 2>/dev/null | tr -cd '\f' | wc -c | tr -d ' ')" \
  'pdftotext reads three pages from the generated PDF'
assert_eq 1 "$(ls -A "$G" | wc -l | tr -d ' ')" 'make-pdf.py writes only OUT'

# --- happy path: two pages, accents, markers, PDF untouched ------------------
D="$(new_sources)"
python3 "$MAKE_PDF" "$D/2026-10-01_brochure.pdf" \
  'Brochure Été 2026, price 1,250 euros' 'Second page'
before="$(sha "$D/2026-10-01_brochure.pdf")"
run_ex "$D/2026-10-01_brochure.pdf"
assert_eq 0 "$EX_STATUS" 'extract: exit 0'
assert_eq "extracted: $D/2026-10-01_brochure.txt" "$EX_OUT" 'extract: stdout names the .txt'
assert_file "$D/2026-10-01_brochure.txt"
assert_grep '^--- page 1 ---$' "$D/2026-10-01_brochure.txt"
assert_grep '^--- page 2 ---$' "$D/2026-10-01_brochure.txt"
assert_grep 'Été' "$D/2026-10-01_brochure.txt"
assert_grep '1,250' "$D/2026-10-01_brochure.txt"
assert_eq "$before" "$(sha "$D/2026-10-01_brochure.pdf")" 'extract: the PDF is unchanged'
assert_eq 0 "$(ls -A "$CASE_TMP" | wc -l | tr -d ' ')" 'extract: TMPDIR left empty'

# --- empty pages are skipped but keep their number ---------------------------
E="$(new_sources)"
python3 "$MAKE_PDF" "$E/gap.pdf" 'Alpha text' '@empty' 'Gamma text'
run_ex "$E/gap.pdf"
assert_eq 0 "$EX_STATUS" 'empty page: exit 0'
assert_grep '^--- page 1 ---$' "$E/gap.txt"
assert_not_grep '^--- page 2 ---$' "$E/gap.txt"
assert_grep '^--- page 3 ---$' "$E/gap.txt"
assert_grep 'Gamma text' "$E/gap.txt"

# --- uppercase .PDF and a path holding spaces --------------------------------
U="$(new_sources)"
python3 "$MAKE_PDF" "$U/Upper Case.PDF" 'Upper text'
run_ex "$U/Upper Case.PDF"
assert_eq 0 "$EX_STATUS" '.PDF: exit 0'
assert_file "$U/Upper Case.txt"
assert_eq "extracted: $U/Upper Case.txt" "$EX_OUT" '.PDF: stdout names the .txt'

# =============================================================================
# Every other exit path (task 2)
# =============================================================================

# --- re-run on an already extracted PDF: exists, untouched --------------------
txt_before="$(sha "$D/2026-10-01_brochure.txt")"
run_ex "$D/2026-10-01_brochure.pdf"
assert_eq 0 "$EX_STATUS" 're-run: exit 0'
assert_eq "exists: $D/2026-10-01_brochure.txt" "$EX_OUT" 're-run: stdout says exists'
assert_eq "$txt_before" "$(sha "$D/2026-10-01_brochure.txt")" 're-run: the .txt is untouched'
tmp_clean 're-run'

# --- a pre-existing .txt of other content is never overwritten ----------------
P="$(new_sources)"
python3 "$MAKE_PDF" "$P/prior.pdf" 'Fresh text'
printf 'HAND-WRITTEN\n' >"$P/prior.txt"
run_ex "$P/prior.pdf"
assert_eq 0 "$EX_STATUS" 'existing .txt: exit 0'
assert_eq "exists: $P/prior.txt" "$EX_OUT" 'existing .txt: stdout says exists'
assert_eq 'HAND-WRITTEN' "$(cat "$P/prior.txt")" 'existing .txt: content untouched'

# --- a dangling symlink at the .txt name: exists, nothing created behind it ---
L="$(new_sources)"
python3 "$MAKE_PDF" "$L/linked.pdf" 'Linked text'
mkdir "$L/elsewhere"
ln -s "$L/elsewhere/dest.txt" "$L/linked.txt"
run_ex "$L/linked.pdf"
assert_eq 0 "$EX_STATUS" 'dangling symlink: exit 0'
assert_eq "exists: $L/linked.txt" "$EX_OUT" 'dangling symlink: stdout says exists'
assert_eq 0 "$(ls -A "$L/elsewhere" | wc -l | tr -d ' ')" 'dangling symlink: nothing created at its destination'
tmp_clean 'dangling symlink'

# --- race: the .txt appears while pdftotext runs; set -C refuses to clobber ---
R="$(new_sources)"
FAKE="$(mktemp -d "$WORK/fake.XXXXXX")"
cat >"$FAKE/pdftotext" <<'FAKE_EOF'
#!/bin/bash
# Fake pdftotext for the race case: creates the target .txt (RACE_TXT) first,
# then writes text to its last argument like the real tool.
printf 'RACE' >"$RACE_TXT"
for last in "$@"; do :; done
printf 'Text from the fake extractor\n' >"$last"
FAKE_EOF
chmod 755 "$FAKE/pdftotext"
python3 "$MAKE_PDF" "$R/race.pdf" 'Race text'
RACE_TXT="$R/race.txt"
export RACE_TXT
EX_PATH="$FAKE:$PATH"
run_ex "$R/race.pdf"
EX_PATH=""
assert_eq 0 "$EX_STATUS" 'race: exit 0'
assert_eq "exists: $R/race.txt" "$EX_OUT" 'race: stdout says exists'
assert_eq 'RACE' "$(cat "$R/race.txt")" 'race: the .txt still holds RACE (set -C refused to clobber)'
tmp_clean 'race'

# --- a scan: exit 65, no text layer, nothing written ---------------------------
S="$(new_sources)"
python3 "$MAKE_PDF" "$S/scan.pdf" '@scan' '@scan'
run_ex "$S/scan.pdf"
assert_eq 65 "$EX_STATUS" 'scan: exit 65'
case "$EX_ERR" in
  *'no text layer'*) TESTS_PASSED=$((TESTS_PASSED + 1)) ;;
  *) echo "FAIL: scan: stderr mentions 'no text layer' (got '$EX_ERR')" >&2; TESTS_FAILED=$((TESTS_FAILED + 1)) ;;
esac
assert_eq 0 "$(ls "$S" | grep -c '\.txt$')" 'scan: no .txt written'
tmp_clean 'scan'

# --- a corrupt PDF (plain text under a .pdf name): exit 1, nothing written ----
C="$(new_sources)"
printf 'this is not a pdf\n' >"$C/corrupt.pdf"
run_ex "$C/corrupt.pdf"
assert_eq 1 "$EX_STATUS" 'corrupt: exit 1'
assert_eq 0 "$(ls "$C" | grep -c '\.txt$')" 'corrupt: no .txt written'
tmp_clean 'corrupt'

# --- usage errors: exit 64, nothing written ------------------------------------
U2="$(new_sources)"
printf 'plain\n' >"$U2/notes.txt"
run_ex
assert_eq 64 "$EX_STATUS" 'no argument: exit 64'
case "$EX_ERR" in
  *usage*) TESTS_PASSED=$((TESTS_PASSED + 1)) ;;
  *) echo "FAIL: no argument: stderr holds a usage line (got '$EX_ERR')" >&2; TESTS_FAILED=$((TESTS_FAILED + 1)) ;;
esac
run_ex "$U2/notes.txt"
assert_eq 64 "$EX_STATUS" 'not a .pdf: exit 64'
run_ex "$U2/missing.pdf"
assert_eq 64 "$EX_STATUS" 'missing .pdf: exit 64'
case "$EX_ERR" in
  *'no such file'*) TESTS_PASSED=$((TESTS_PASSED + 1)) ;;
  *) echo "FAIL: missing .pdf: stderr says 'no such file' (got '$EX_ERR')" >&2; TESTS_FAILED=$((TESTS_FAILED + 1)) ;;
esac
assert_eq 1 "$(ls -A "$U2" | wc -l | tr -d ' ')" 'usage errors: nothing written'
tmp_clean 'usage'

# --- pdftotext hidden from PATH: exit 69, install hint, nothing written (D-15) -
H="$(new_sources)"
python3 "$MAKE_PDF" "$H/hidden.pdf" 'Hidden text'
h_before="$(sha "$H/hidden.pdf")"
NOTOOL="$(mktemp -d "$WORK/notool.XXXXXX")"
EX_PATH="$NOTOOL"
run_ex "$H/hidden.pdf"
EX_PATH=""
assert_eq 69 "$EX_STATUS" 'pdftotext hidden: exit 69'
case "$EX_ERR" in
  *'pdftotext not found'*) TESTS_PASSED=$((TESTS_PASSED + 1)) ;;
  *) echo "FAIL: hidden: stderr says 'pdftotext not found' (got '$EX_ERR')" >&2; TESTS_FAILED=$((TESTS_FAILED + 1)) ;;
esac
case "$EX_ERR" in
  *'brew install poppler'*) TESTS_PASSED=$((TESTS_PASSED + 1)) ;;
  *) echo "FAIL: hidden: stderr names 'brew install poppler' (got '$EX_ERR')" >&2; TESTS_FAILED=$((TESTS_FAILED + 1)) ;;
esac
case "$EX_ERR" in
  *'apt-get install poppler-utils'*) TESTS_PASSED=$((TESTS_PASSED + 1)) ;;
  *) echo "FAIL: hidden: stderr names 'apt-get install poppler-utils' (got '$EX_ERR')" >&2; TESTS_FAILED=$((TESTS_FAILED + 1)) ;;
esac
assert_eq 2 "$(printf '%s\n' "$EX_ERR" | wc -l | tr -d ' ')" 'pdftotext hidden: exactly two stderr lines'
assert_eq 0 "$(ls "$H" | grep -c '\.txt$')" 'pdftotext hidden: no .txt written'
assert_eq "$h_before" "$(sha "$H/hidden.pdf")" 'pdftotext hidden: the PDF is unchanged'
tmp_clean 'pdftotext hidden'

# --- a file name starting with a dash is never read as an option ---------------
DASH="$(new_sources)"
python3 "$MAKE_PDF" "$DASH/-dash.pdf" 'Dash text'
cd "$DASH" || exit 2
run_ex -dash.pdf
cd "$REPO_ROOT" || exit 2
assert_eq 0 "$EX_STATUS" '-dash.pdf: exit 0'
assert_eq 'extracted: -dash.txt' "$EX_OUT" '-dash.pdf: stdout names the .txt'
assert_file "$DASH/-dash.txt"
assert_grep 'Dash text' "$DASH/-dash.txt"
tmp_clean '-dash.pdf'

# --- static checks on the script ------------------------------------------------
assert_grep 'set -C' "$SCRIPT"
assert_grep 'pdftotext -enc UTF-8 --' "$SCRIPT"
assert_eq 0 "$(grep -c -e '-layout' "$SCRIPT" || true)" 'script does not use pdftotext layout mode'
assert_eq 0 "$(grep -c -e '-nopgbrk' "$SCRIPT" || true)" 'script keeps pdftotext page breaks'
assert_eq 0 "$(grep -cE '[A-Za-z_]+=\(|\$\{[A-Za-z_]+\[|declare -[aA]' "$SCRIPT" || true)" 'script uses no bash array syntax (bash 3.2)'
assert_eq 0 "$(grep -cE 'git clean|rm -rf' "$SCRIPT" || true)" 'script has no destructive recursive command'
case "$(head -n 1 "$SCRIPT")" in
  '#!/usr/bin/env bash') TESTS_PASSED=$((TESTS_PASSED + 1)) ;;
  *) echo 'FAIL: script shebang is #!/usr/bin/env bash' >&2; TESTS_FAILED=$((TESTS_FAILED + 1)) ;;
esac

finish
